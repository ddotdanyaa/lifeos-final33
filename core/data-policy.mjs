// Политика данных — один переключатель на всю систему. Решение владельца 2026-07-30, его словами:
// «OCR может быть без сети, может быть с сетью синхронизации. Вообще по-разному может все быть...
// Короче, это такой вот тумблер, который можно перетягивать в разные стороны».
// Два полюса он описал так: полностью локально — «долго, неудобно, зато максимально безопасно»;
// с сетью — «максимально быстро, но учитывая, что у нас нет сейчас больших денег для инвестиций,
// это почти небезопасно». Поэтому вопрос «а этой функции можно в сеть?» поставлен неправильно:
// правило одно, и оно принадлежит владельцу, а не функции.
//
// Здесь только чистая часть: список режимов и определение «внешнего» адреса. Чтение состояния и
// отказ с причиной живут в app.js.

export const DATA_POLICY_MODES = ["local-only", "network-allowed"];

// «Внешний» — значит за пределами этого компьютера и его локальной сети. Локальная модель на
// 127.0.0.1, локальный прокси сервера и относительные пути НЕ внешние: в режиме «полностью
// локально» они обязаны продолжать работать, иначе тумблер выключал бы не сеть, а сам продукт.
// Нераспознанный адрес считаем внешним: ошибаться безопаснее в сторону приватности.
export function isExternalEndpoint(url) {
  const raw = String(url || "").trim();
  if (!raw || raw.startsWith("/") || raw.startsWith("./") || raw.startsWith("../")) return false;
  let host = "";
  try {
    host = new URL(raw, "http://127.0.0.1").hostname.toLowerCase();
  } catch {
    return true;
  }
  if (!host || host === "localhost" || host === "0.0.0.0" || host === "::1" || host.endsWith(".local") || host.endsWith(".localhost")) return false;
  if (/^127\./.test(host) || /^10\./.test(host) || /^192\.168\./.test(host)) return false;
  if (/^172\.(1[6-9]|2\d|3[01])\./.test(host)) return false;
  return true;
}

// Режим из хранилища, с безопасным значением по умолчанию: локально. Безопасное значение не
// должно требовать действия владельца.
export function normalizeDataPolicyMode(mode) {
  const clean = String(mode || "").trim();
  return DATA_POLICY_MODES.includes(clean) ? clean : "local-only";
}
