// САМООБУЧЕНИЕ ПРОДУКТА ЧЕРЕЗ ГОЛОС ВЛАДЕЛЬЦА.
//
// Владелец 2026-08-01: «самое главное — самообучающийся сценарий. Если его сделать, то всё
// остальное, что я захочу изменить, будет постепенно после каждого дня моих голосовых
// улучшаться».
//
// Что для этого не хватало. Система уже училась ранжировать предложения по его решениям
// (журнал → калибровка → профиль). Но когда он говорил про САМУ СИСТЕМУ — «инсайты непонятные»,
// «микрофон не работает», «хочу кнопку разобрать с ИИ» — это падало в общую кучу мыслей и
// умирало там. Самая ценная обратная связь в продукте обрабатывалась хуже всего.
//
// Здесь мысль о продукте узнаётся и становится отдельным объектом: с цитатой, с типом
// («сломано» / «непонятно» / «хочу») и с датой. Дальше её видит и владелец в Контроле, и тот,
// кто пишет код.
//
// ГРАНИЦА, которую нельзя переходить: система НЕ чинит себя сама и не притворяется, что может.
// Она узнаёт, называет и копит. Код по этим записям пишет человек — просто теперь он получает
// их списком с цитатами, а не выуживает из двадцати голосовых за неделю.
//
// Модуль чистый: ни state, ни DOM. Поэтому проверяется без браузера.

// Владелец говорит о системе её ЖИВЫМИ именами, а не техническими. «Разбор», «инсайты»,
// «связи» — так называются экраны, которые он видит. Добавлять сюда служебные слова
// («репозиторий», «коллекция») бессмысленно: он ими не пользуется.
const PRODUCT_WORDS = [
  "lifeos", "лайфос", "систем", "приложени", "программ",
  "экран", "кнопк", "интерфейс", "разбор", "инсайт", "связ", "график",
  "микрофон", "запис", "поиск", "календар", "чат", "граф", "заметк", "оллам", "модел"
];

// Оценка или желание. Без них упоминание системы — просто упоминание: «записал в LifeOS» это
// не обратная связь, а факт.
const COMPLAINT_WORDS = [
  "не работает", "не пашет", "сломал", "не открывает", "не находит", "не показывает",
  "непонятн", "не понимаю", "криво", "плохо", "ужасн", "бесит", "раздража", "неудобн",
  "тупо", "мусор", "лишн", "зачем"
];

const WISH_WORDS = [
  "хочу чтоб", "хочу что", "надо чтоб", "нужно чтоб", "должно быть", "должен быть",
  "добавь", "сделай", "не хватает", "было бы", "пусть будет", "лучше бы"
];

const QUESTION_WORDS = ["почему", "как сделать", "а можно", "можно ли"];

function has(lower, words) {
  return words.some((word) => lower.includes(word));
}

// Тип обратной связи. Порядок проверки неслучаен: «не работает» важнее «хочу», потому что
// сломанное блокирует использование, а желание — нет. Если владелец сказал и то и другое в
// одной фразе, наверх идёт поломка.
function feedbackKind(lower) {
  if (has(lower, COMPLAINT_WORDS)) return "сломано или непонятно";
  if (has(lower, WISH_WORDS)) return "хочу иначе";
  if (has(lower, QUESTION_WORDS)) return "вопрос к системе";
  return "";
}

// Разбор идёт ПО ПРЕДЛОЖЕНИЯМ, а не по всему тексту: владелец в одной надиктовке говорит и про
// смену в такси, и про то, что инсайты непонятные. Взять весь текст целиком значит либо потерять
// вторую мысль, либо приписать первой то, чего в ней нет. Цитата обязана быть той фразой, где
// он это сказал (И-6), иначе объяснить своё решение системе будет нечем.
function sentences(text) {
  return String(text || "")
    .split(/(?<=[.!?…])\s+|\n+/u)
    .map((line) => line.trim())
    .filter((line) => line.length >= 12);
}

export function detectProductFeedback(text) {
  const found = [];
  for (const sentence of sentences(text)) {
    const lower = sentence.toLocaleLowerCase("ru-RU");
    if (!has(lower, PRODUCT_WORDS)) continue;
    const kind = feedbackKind(lower);
    // Упомянул систему без оценки — это не обратная связь. Записывать такое значит утопить
    // настоящие замечания в шуме, и через неделю список станет нечитаемым.
    if (!kind) continue;
    found.push({
      kind,
      // Заголовок — его же слова, укороченные. Пересказывать своими нельзя: он потом должен
      // узнать в списке собственную фразу, а не наш вывод о ней.
      title: sentence.length > 90 ? sentence.slice(0, 87).trimEnd() + "…" : sentence,
      quote: sentence
    });
  }
  // Больше трёх замечаний из одной надиктовки — почти всегда признак того, что сработали слова,
  // а не смысл. Берём первые три: они ближе к началу мысли, где владелец говорит главное.
  return found.slice(0, 3);
}

// Свод для того, кто пишет код. Не отчёт о системе — СПИСОК РАБОТЫ, отсортированный так, как
// его будут делать: сначала сломанное, потом непонятное, потом пожелания.
const KIND_ORDER = ["сломано или непонятно", "хочу иначе", "вопрос к системе"];

export function groupProductFeedback(rows) {
  const list = Array.isArray(rows) ? rows.filter(Boolean) : [];
  return KIND_ORDER
    .map((kind) => ({ kind, rows: list.filter((row) => row.kind === kind) }))
    .filter((group) => group.rows.length);
}
