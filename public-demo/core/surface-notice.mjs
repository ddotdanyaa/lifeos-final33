// Ответ экрана на нажатие — и слова, которыми он отвечает.
//
// Замер 2026-07-30 (`tools/audit-liveness.mjs`) нашёл на четырёх экранах пять контролов, после
// нажатия на которые не менялось НИЧЕГО: ни разметка, ни активный экран, ни адрес, ни холст, ни
// тост. Причина у всех пяти оказалась одна и та же, и она не «кнопка не подключена»: обработчик
// честно отрабатывал и честно решал ничего не менять — режим уже выбран, вкладка уже открыта,
// поле пустое. Правильная работа была неотличима от поломки, потому что о ней не сообщали.
//
// `state.commandMessage` для этого не годится: он рисуется только на Доме, а нажимают на
// Контроле, в Чате, у агентов и в Календаре. Записка привязана к экрану — показывается там, где
// нажали, и заменяется следующим нажатием, а не копится.
//
// Здесь только чистая часть: форма записки и весь текст. Запись в состояние — в app.js.

export const EMPTY_SURFACE_NOTICE = { surface: "", text: "", at: "" };

export function normalizeSurfaceNotice(value) {
  const source = value && typeof value === "object" ? value : {};
  return {
    surface: String(source.surface || "").trim(),
    text: String(source.text || "").trim(),
    at: String(source.at || "").trim()
  };
}

// ── Контроль · тумблер политики данных ─────────────────────────────────────────────────────
// Нажатие на уже включённый полюс — не ошибка владельца: так он спрашивает «а сейчас-то как?».
// Отказ от подтверждения — тоже результат, и он обязан быть виден, иначе закрытое окно
// подтверждения выглядит ровно как кнопка, которая ничего не делает.
export function dataPolicyNoticeText(kind, mode) {
  const local = mode !== "network-allowed";
  if (kind === "declined") {
    return "Режим не изменён: переход к обращениям наружу отменён. Всё по-прежнему остаётся на этом компьютере.";
  }
  if (kind === "same") {
    return local
      ? "Уже так: всё остаётся на этом компьютере. Ничего не изменилось — чтобы разрешить обращения наружу, нажми соседний вариант."
      : "Уже так: обращения наружу разрешены. Ничего не изменилось — чтобы всё закрыть, нажми соседний вариант.";
  }
  return local
    ? "Теперь всё остаётся на этом компьютере: обращения наружу не отправляются."
    : "Обращения наружу разрешены. Каждое из них видно в Контроле и попадает в чеки.";
}

// ── Календарь · вкладки вида ───────────────────────────────────────────────────────────────
// Вид по умолчанию — день, поэтому нажатие на «Сегодня» на свежем экране законно ничего не
// меняло: вкладка уже была активной. Отвечаем тем, что видно сейчас, и куда ведёт соседняя.
export function calendarViewNoticeText(view, alreadyOpen) {
  if (view === "month") {
    return alreadyOpen
      ? "Уже открыт месяц. Соседняя вкладка «Сегодня» возвращает к плану одного дня по часам."
      : "Открыт месяц: тот же план сеткой по дням.";
  }
  return alreadyOpen
    ? "Уже открыт день: план на сегодня по часам. Соседняя вкладка «Месяц» показывает тот же план сеткой."
    : "Открыт день: план на сегодня по часам.";
}

// ── Агенты · «Сохранить время» ─────────────────────────────────────────────────────────────
// Пустое поле «Время» — обычный случай, и раньше кнопка молчала именно в нём. Говорим, чего не
// хватает. §7: сохранённое расписание не даёт агенту запускаться самому — он только предложит.
export function agentScheduleNoticeText(kind, agentName, time) {
  if (kind === "unknown-agent") return "Такого агента нет — расписание сохранять не для кого.";
  if (kind === "no-field") return "Расписание не сохранено: поля «Время» нет на экране — открой карточку агента «" + agentName + "» целиком.";
  if (kind === "empty-time") return "Расписание не сохранено: в поле «Время» рядом с агентом «" + agentName + "» нужно время вида 07:30. Сейчас оно пустое.";
  return "Расписание сохранено: агент «" + agentName + "» в " + time + " предложит запуск. Сам он не запускается — решение остаётся за тобой.";
}

// ── Чат · «Отправить» с пустым полем ───────────────────────────────────────────────────────
// Отправлять нечего — но и молчать нельзя: именно здесь кнопка выглядела мёртвой. Заодно честно
// называем, чем сейчас отвечает чат: локальная модель либо реально проверена генерацией, либо не
// запущена, и второе не маскируем (§7 — провайдер не имитирует успех).
export function chatEmptySendNoticeText(ollama) {
  const source = ollama && typeof ollama === "object" ? ollama : {};
  const model = String(source.selectedModel || "").trim();
  const ready = String(source.status || "").trim() === "generation_ok" && model;
  return ready
    ? "Отправлять нечего: поле пустое. Напиши вопрос — отвечу локальной моделью " + model + " на этом компьютере."
    : "Отправлять нечего: поле пустое. Локальная модель не запущена — на вопросы отвечаю правилами по твоим данным, это работает уже сейчас. Чтобы включить модель: запусти Ollama и нажми «Проверить», потом «Тест» в строке над диалогом.";
}
